// Look and feel comes entirely from src/PanelTheme.hpp and src/Toll/Panel.hpp,
// generated by tools/panels/Toll.py -- see ../../panelkit/README.md.

struct TollWidget : ModuleWidget {
	TollWidget(TollModule* module) {
		setModule(module);
		setPanel(createPanel(asset::plugin(pluginInstance, "res/Toll.svg")));

		panel::addScrews(this);
		panel::addLabels(this);

		addInput(createInputCentered<panel::PortTrigInMain>(panel::mm(panel::TRIG_POS.x, panel::TRIG_POS.y), module, TollModule::TRIG_INPUT));
		addInput(createInputCentered<panel::PortIn>(panel::mm(panel::VOCT_POS.x, panel::VOCT_POS.y), module, TollModule::VOCT_INPUT));
		addChild(createLightCentered<SmallLight<panel::PaperLight> >(
			panel::mm(panel::HIT_LED_POS.x, panel::HIT_LED_POS.y), module, TollModule::HIT_LIGHT));

		addParam(createParamCentered<RoundLargeBlackKnob>(panel::mm(panel::TUNE_POS.x, panel::TUNE_POS.y), module, TollModule::TUNE_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::SET_POS.x, panel::SET_POS.y), module, TollModule::SET_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::BUZZ_POS.x, panel::BUZZ_POS.y), module, TollModule::BUZZ_PARAM));

		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::DECAY_POS.x, panel::DECAY_POS.y), module, TollModule::DECAY_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::DAMP_POS.x, panel::DAMP_POS.y), module, TollModule::DAMP_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::BEND_POS.x, panel::BEND_POS.y), module, TollModule::BEND_PARAM));

		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::STRIKE_POS.x, panel::STRIKE_POS.y), module, TollModule::STRIKE_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::HARD_POS.x, panel::HARD_POS.y), module, TollModule::HARD_PARAM));
		addParam(createParamCentered<RoundBlackKnob>(panel::mm(panel::SPREAD_POS.x, panel::SPREAD_POS.y), module, TollModule::SPREAD_PARAM));

		addInput(createInputCentered<panel::PortIn>(panel::mm(panel::SPREAD_CV_POS.x, panel::SPREAD_CV_POS.y), module, TollModule::SPREAD_CV_INPUT));
		addInput(createInputCentered<panel::PortIn>(panel::mm(panel::BEND_CV_POS.x, panel::BEND_CV_POS.y), module, TollModule::BEND_CV_INPUT));
		// TRIG and CHOKE are gates; V/OCT and the three CV jacks are levels.
		addInput(createInputCentered<panel::PortTrigIn>(panel::mm(panel::CHOKE_POS.x, panel::CHOKE_POS.y), module, TollModule::CHOKE_INPUT));
		addInput(createInputCentered<panel::PortIn>(panel::mm(panel::STRIKE_CV_POS.x, panel::STRIKE_CV_POS.y), module, TollModule::STRIKE_CV_INPUT));
		addInput(createInputCentered<panel::PortIn>(panel::mm(panel::DECAY_CV_POS.x, panel::DECAY_CV_POS.y), module, TollModule::DECAY_CV_INPUT));
		addOutput(createOutputCentered<panel::PortOutMain>(panel::mm(panel::OUT_POS.x, panel::OUT_POS.y), module, TollModule::OUT_OUTPUT));
	}
};


Model* modelToll = createModel<TollModule, TollWidget>("Toll");
